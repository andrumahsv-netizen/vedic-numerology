// Вспомогательная функция сворачивания чисел
function strictReduceDigit(num) {
    if (!num) return 0;
    const parsed = parseInt(num, 10);
    if (isNaN(parsed) || parsed === 0) return 0;
    return ((parsed - 1) % 9) + 1;
}

/**
 * ИСПРАВЛЕННЫЙ расчет совместимости.
 * ТЕПЕРЬ принимает конкретные day и month из текущего контекста интерфейса (календаря)
 */
export function getAdvancedRelationTip(targetBirthDateStr, userMoolank, role = 'partner', currentDayContext = null) {
    if (!targetBirthDateStr || !userMoolank) return null;

    // 1. Извлекаем Число Души близкого человека БЕЗ багов Date()
    const parts = targetBirthDateStr.split('-');
    if (parts.length < 3) return null;
    const targetDay = parseInt(parts[2], 10);
    const targetSoulNum = strictReduceDigit(targetDay);

    // 2. Определяем, для какого дня мы считаем отношения
    // Если контекст дня не передан, берем реальное текущее число (но безопасно по местному времени)
    let dayForCalculation = currentDayContext;
    if (!dayForCalculation) {
        dayForCalculation = new Date().getDate(); 
    }

    // 3. Вычисляем Вибрацию Дня для БЛИЗКОГО человека
    // Формула: Число Души близкого + Текущий просматриваемый день
    const targetDayCode = strictReduceDigit(targetSoulNum + dayForCalculation);

    // 4. Достаем нужную карточку подсказки из базы данных
    const roleDb = COMPREHENSIVE_DB[role];
    if (!roleDb || !roleDb[targetSoulNum]) return null;

    const tipText = roleDb[targetSoulNum][targetDayCode];

    return {
        targetSoulNum,
        targetDayCode,
        tip: tipText || "Сбалансированный транзит для построения коммуникации."
    };
}